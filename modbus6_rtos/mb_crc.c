/*=============================================================
 * Modbus-RTU CRC16 校验模块 (mb_crc.c)
 *-------------------------------------------------------------
 * 算法: 循环冗余校验, 多项式 0xA001 (即 0x8005 的反转形式)
 *       初值 0xFFFF, 低位先移 (LSB-first), 无最终异或
 * 结果: u16 返回值, Modbus-RTU 规定发送时【低字节在前、高字节在后】
 * 适用: 本工程所有 Modbus 帧 —— 主站轮询帧(sensors.c)、
 *       从站应答帧(screen.c) 的收发两端统一调用本函数
 *=============================================================*/
#include "Config.h"

/* 计算 Modbus-RTU CRC16
 * p   : 数据首指针 (地址+功能码+数据, 不含 CRC 字段)
 * len : 参与校验的字节数
 * 返回: 16 位 CRC, 附加到帧尾时低字节在前 */
u16 mb_crc16(const u8 *p, u8 len)
{
    u16 crc = 0xFFFF;   /* CRC 初值 */
    u8 i, j;

    for (i = 0; i < len; i++) {
        crc ^= (u16)p[i];              /* 与当前字节异或 */
        for (j = 0; j < 8; j++) {      /* 每字节处理 8 次 */
            if (crc & 0x0001) { crc >>= 1; crc ^= 0xA001; }  /* 最低位为1: 移位+异或多项式 */
            else              { crc >>= 1; }                  /* 最低位为0: 仅移位 */
        }
    }
    return crc;   /* 返回 CRC 值 (低字节先发, 高字节后发) */
}