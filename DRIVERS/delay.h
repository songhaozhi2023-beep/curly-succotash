#ifndef __DELAY_H        // 头文件保护宏，防止重复包含
#define __DELAY_H        // 定义头文件标识符

#include "config.h"      // 包含系统配置头文件，定义基本数据类型和系统配置

/*
 * 微秒级延时函数
 * 功能：基于24MHz时钟频率的精确微秒级延时
 * 参数：us - 需要延时的微秒数 (u16类型)
 * 返回值：无
 * 注意事项：该函数使用内部循环实现延时，会占用CPU资源
 */
void delay_us(u16 us);   // 函数声明：微秒级延时函数，参数为延时微秒数

/*
 * 毫秒级延时函数
 * 功能：毫秒级延时函数，基于内部循环实现
 * 参数：ms - 需要延时的毫秒数 (u16类型)
 * 返回值：无
 * 注意事项：该函数使用内部循环实现延时，会占用CPU资源
 */
void delay_ms(u16 ms);   // 函数声明：毫秒级延时函数，参数为延时毫秒数

#endif                 // 头文件结束标识